// One URL shape for every page on this site.
//
// Astro builds each page as `<path>/index.html`, so the canonical URL of a
// post is `/blog/<slug>/` (with a trailing slash), and that is what the
// canonical link, JSON-LD and sitemap use. Internal links must use the same
// form: the slashless form is redirected by Cloudflare's static asset
// handling, which costs every click an extra round trip.
//
// @yamblog/core's generators build post URLs without a trailing slash
// (changing that default would change RSS guids for every user), so the
// feed and llms.txt routes post-process their output with the helpers below.

export const BLOG_PATH = '/blog';

/** Root-relative path of the blog index: `/blog/`. */
export const blogIndexPath = (): string => `${BLOG_PATH}/`;

/** Root-relative path of a post: `/blog/<slug>/`. */
export const postPath = (slug: string): string => `${BLOG_PATH}/${slug}/`;

const trimSite = (siteUrl: string): string => siteUrl.replace(/\/+$/, '');

/** Absolute canonical URL of a post: `<site>/blog/<slug>/`. */
export const postUrl = (siteUrl: string, slug: string): string =>
  `${trimSite(siteUrl)}${postPath(slug)}`;

/**
 * Rewrites the `<link>` elements of an RSS document generated by
 * `blog.generateRss()` to the trailing-slash form. `<guid>` values are left
 * as they are on purpose: changing a guid makes feed readers deliver every
 * post again as a new item.
 */
export function canonicalizeFeedLinks(xml: string, siteUrl: string, slugs: readonly string[]): string {
  const site = trimSite(siteUrl);
  let out = xml.replaceAll(`<link>${site}${BLOG_PATH}</link>`, `<link>${site}${blogIndexPath()}</link>`);
  for (const slug of slugs) {
    out = out.replaceAll(`<link>${site}${BLOG_PATH}/${slug}</link>`, `<link>${postUrl(site, slug)}</link>`);
  }
  return out;
}

/**
 * Rewrites the post links of an llms.txt section generated by
 * `blog.generateLlmsTxt()` (`- [Title](<site>/blog/<slug>)`) to the
 * trailing-slash form.
 */
export function canonicalizeLlmsLinks(text: string, siteUrl: string, slugs: readonly string[]): string {
  const site = trimSite(siteUrl);
  let out = text;
  for (const slug of slugs) {
    out = out.replaceAll(`](${site}${BLOG_PATH}/${slug})`, `](${postUrl(site, slug)})`);
  }
  return out;
}
